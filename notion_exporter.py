"""
notion_exporter.py — Real Notion API Integration for I.A.M. NoteWorthy
Syncs structured lecture notes, exam alerts, key concepts, and timelines directly to Notion.
"""

import os
import re
import requests
from typing import Dict, Any, Optional

def clean_notion_id(raw_id: Optional[str]) -> Optional[str]:
    """Extract standard UUID from Notion URL or raw string."""
    if not raw_id:
        return None
    raw_id = str(raw_id).strip()
    match = re.search(r'([0-9a-fA-F]{32}|[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12})', raw_id)
    if match:
        v = match.group(1).replace('-', '')
        return f"{v[0:8]}-{v[8:12]}-{v[12:16]}-{v[16:20]}-{v[20:32]}"
    return raw_id


def truncate_text(text: str, max_len: int = 1950) -> str:
    if not text:
        return ""
    text = str(text)
    return text if len(text) <= max_len else text[:max_len] + "…"


def build_rich_text(content: str, bold: bool = False, italic: bool = False, color: str = "default") -> list:
    return [{
        "type": "text",
        "text": {"content": truncate_text(content)},
        "annotations": {
            "bold": bold,
            "italic": italic,
            "color": color
        }
    }]


def build_notion_blocks(notes: dict) -> list:
    """Converts I.A.M. NoteWorthy note structure into Notion API Block objects."""
    blocks = []

    # 1. Overview Callout
    subject = notes.get("subject", "General Lecture")
    date_str = notes.get("date", "Today")
    duration = notes.get("duration", notes.get("duration_text", "Session"))
    lang = notes.get("language_detected", notes.get("language", "Multilingual (Hindi + English)"))

    meta_text = f"📚 {subject}  •  📅 {date_str}  •  ⏱️ Duration: {duration}  •  🌐 Language: {lang}\nGenerated by I.A.M. NoteWorthy Smart Lecture Intelligence"
    blocks.append({
        "object": "block",
        "type": "callout",
        "callout": {
            "rich_text": build_rich_text(meta_text),
            "icon": {"type": "emoji", "emoji": "🎓"},
            "color": "green_background"
        }
    })

    blocks.append({"object": "block", "type": "divider", "divider": {}})

    # 2. Exam Alerts (High-Yield Focus)
    exam_alerts = notes.get("exam_alerts", [])
    if exam_alerts:
        blocks.append({
            "object": "block",
            "type": "heading_2",
            "heading_2": {
                "rich_text": build_rich_text("🎯 High-Yield Exam Topics", bold=True, color="red")
            }
        })

        for alert in exam_alerts:
            topic = alert.get("topic", "Critical Concept")
            ts = alert.get("timestamp", "00:00")
            importance = alert.get("importance", "Critical")
            phrase = alert.get("trigger_phrase", "")
            tip = alert.get("instructor_tip", "")

            callout_text = f"[{ts}] {importance.upper()}: {topic}\n"
            if phrase:
                callout_text += f'“{phrase}”\n'
            if tip:
                callout_text += f"💡 Instructor Exam Tip: {tip}"

            blocks.append({
                "object": "block",
                "type": "callout",
                "callout": {
                    "rich_text": build_rich_text(callout_text),
                    "icon": {"type": "emoji", "emoji": "🚨"},
                    "color": "red_background"
                }
            })

    # 3. Key Concepts
    key_concepts = notes.get("key_concepts", notes.get("concepts", []))
    if key_concepts:
        blocks.append({
            "object": "block",
            "type": "heading_2",
            "heading_2": {
                "rich_text": build_rich_text("💡 Key Concepts & Core Terminology", bold=True)
            }
        })

        for c in key_concepts:
            if isinstance(c, dict):
                tag = c.get("tag", c.get("name", "Concept"))
                desc = c.get("description", "")
            else:
                tag = str(c)
                desc = ""

            rich = [
                {"type": "text", "text": {"content": f"{tag}: "}, "annotations": {"bold": True, "color": "purple"}},
                {"type": "text", "text": {"content": truncate_text(desc)}}
            ]

            blocks.append({
                "object": "block",
                "type": "bulleted_list_item",
                "bulleted_list_item": {"rich_text": rich}
            })

    # 4. Executive Summary
    summary = notes.get("executive_summary", notes.get("summary", ""))
    if summary:
        blocks.append({
            "object": "block",
            "type": "heading_2",
            "heading_2": {
                "rich_text": build_rich_text("📝 Executive Summary", bold=True)
            }
        })

        # Split into paragraphs if long
        paragraphs = [p.strip() for p in summary.split("\n\n") if p.strip()]
        if not paragraphs:
            paragraphs = [summary]

        for p in paragraphs:
            blocks.append({
                "object": "block",
                "type": "paragraph",
                "paragraph": {"rich_text": build_rich_text(p)}
            })

    # 5. Hinglish & Classroom Clarifications Glossary
    glossary = notes.get("hinglish_glossary", [])
    if glossary:
        blocks.append({
            "object": "block",
            "type": "heading_2",
            "heading_2": {
                "rich_text": build_rich_text("📖 Smart Glossary (Classroom Explanations ➔ Textbook Standard)", bold=True)
            }
        })

        for item in glossary:
            classroom = item.get("classroom_phrase", "")
            formal = item.get("formal_term", "")
            explanation = item.get("explanation", "")

            rich = [
                {"type": "text", "text": {"content": f'"{classroom}" '}, "annotations": {"italic": True, "color": "orange"}},
                {"type": "text", "text": {"content": "➔ "}},
                {"type": "text", "text": {"content": f"{formal}: "}, "annotations": {"bold": True, "color": "blue"}},
                {"type": "text", "text": {"content": truncate_text(explanation)}}
            ]

            blocks.append({
                "object": "block",
                "type": "bulleted_list_item",
                "bulleted_list_item": {"rich_text": rich}
            })

    # 6. Lecture Timeline & Slides
    timeline = notes.get("timeline", [])
    if timeline:
        blocks.append({
            "object": "block",
            "type": "heading_2",
            "heading_2": {
                "rich_text": build_rich_text("⏱️ Chronological Timeline & Visual Slide Context", bold=True)
            }
        })

        for item in timeline:
            ts = item.get("timestamp", "00:00")
            heading = item.get("heading", "Topic Discussion")
            item_summary = item.get("summary", "")
            visual = item.get("visual_context", "")

            content = f"[{ts}] {heading}: {item_summary}"
            if visual:
                content += f"\n🖼️ Board/Slide Note: {visual}"

            blocks.append({
                "object": "block",
                "type": "bulleted_list_item",
                "bulleted_list_item": {"rich_text": build_rich_text(content)}
            })

    # 7. Action Items
    action_items = notes.get("action_items", [])
    if action_items:
        blocks.append({
            "object": "block",
            "type": "heading_2",
            "heading_2": {
                "rich_text": build_rich_text("✅ Next Steps & Student Action Items", bold=True)
            }
        })

        for task in action_items:
            blocks.append({
                "object": "block",
                "type": "to_do",
                "to_do": {
                    "rich_text": build_rich_text(str(task)),
                    "checked": False
                }
            })

    # Notion blocks array limit is 100 per API call
    return blocks[:100]


def export_to_notion(
    note_payload: Dict[str, Any],
    api_key: Optional[str] = None,
    parent_id: Optional[str] = None
) -> Dict[str, Any]:
    """
    Exports lecture notes to Notion workspace via official Notion API.
    Handles token authentication, auto-resolving parent pages, and block serialization.
    """
    token = (api_key or "").strip() or os.getenv("NOTION_API_KEY", "").strip()
    if not token:
        return {
            "success": False,
            "error_code": "NO_TOKEN",
            "message": "Notion API Token is required. Please provide your Internal Integration Secret (starts with 'secret_')."
        }

    headers = {
        "Authorization": f"Bearer {token}",
        "Content-Type": "application/json",
        "Notion-Version": "2022-06-28"
    }

    # Normalize note object
    notes = note_payload.get("notes", note_payload)
    title = note_payload.get("title") or notes.get("title") or "Lecture Notes"

    target_parent_id = clean_notion_id(parent_id or os.getenv("NOTION_PAGE_ID", ""))

    # If no parent_id was provided, search for accessible pages in the integration
    if not target_parent_id:
        try:
            search_res = requests.post(
                "https://api.notion.com/v1/search",
                headers=headers,
                json={"filter": {"value": "page", "property": "object"}, "page_size": 1},
                timeout=10
            )
            if search_res.status_code == 200:
                results = search_res.json().get("results", [])
                if results:
                    target_parent_id = results[0].get("id")
        except Exception:
            pass

    if not target_parent_id:
        return {
            "success": False,
            "error_code": "NO_PARENT",
            "message": (
                "Could not find a parent Notion page. Please provide your Notion Page ID or URL, "
                "and make sure you shared that page with your integration (click '...' -> Connect to -> select your integration)."
            )
        }

    # Build blocks
    blocks = build_notion_blocks(notes)

    # Prepare page creation payload
    # Check if target is page or database
    payload = {
        "parent": {"page_id": target_parent_id},
        "icon": {"type": "emoji", "emoji": "📝"},
        "properties": {
            "title": {
                "title": [
                    {
                        "type": "text",
                        "text": {"content": truncate_text(title, 200)}
                    }
                ]
            }
        },
        "children": blocks
    }

    try:
        res = requests.post("https://api.notion.com/v1/pages", headers=headers, json=payload, timeout=20)
        
        # If page_id failed because parent is a database
        if res.status_code == 400 and "database_id" in res.text:
            payload["parent"] = {"database_id": target_parent_id}
            payload["properties"] = {
                "Name": {
                    "title": [
                        {
                            "type": "text",
                            "text": {"content": truncate_text(title, 200)}
                        }
                    ]
                }
            }
            res = requests.post("https://api.notion.com/v1/pages", headers=headers, json=payload, timeout=20)

        if res.status_code in (200, 201):
            data = res.json()
            page_url = data.get("url") or f"https://notion.so/{data.get('id', '').replace('-', '')}"
            return {
                "success": True,
                "url": page_url,
                "id": data.get("id"),
                "message": f"Successfully exported '{title}' to Notion!"
            }
        else:
            err_data = {}
            try:
                err_data = res.json()
            except Exception:
                pass

            err_code = err_data.get("code", f"HTTP_{res.status_code}")
            err_msg = err_data.get("message", res.text)

            if res.status_code == 401:
                return {
                    "success": False,
                    "error_code": "UNAUTHORIZED",
                    "message": "Invalid Notion token. Please verify your integration secret."
                }
            elif res.status_code == 404 or "object_not_found" in err_code:
                return {
                    "success": False,
                    "error_code": "NOT_FOUND",
                    "message": (
                        "Parent page not found. Please ensure you have added your integration connection to the page "
                        "(click '...' on the top right of your Notion page -> 'Connect to' -> select your integration)."
                    )
                }

            return {
                "success": False,
                "error_code": err_code,
                "message": f"Notion API error: {err_msg}"
            }

    except Exception as e:
        return {
            "success": False,
            "error_code": "REQUEST_FAILED",
            "message": f"Failed to connect to Notion: {str(e)}"
        }
